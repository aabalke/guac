// DMG Compatibility palettes

func (gb *GameBoy) setCompPalette() {
	pals := compPalettes[gb.getCompPaletteId()]

	// pattern 0x7FFF for bg not in use
	// set bg palette
	gb.Write(0xFF68, 0x80)
	for i := range uint8(0x40) {
		if i < 8 {
			gb.Write(0xFF69, uint8(pals[0][i>>1]>>((i&1)*8)))
			continue
		}

		gb.Write(0xFF69, 0xFF&^((i&1)<<7))
	}

	// set obj palette 1
	gb.Write(0xFF6A, 0x80)
	for i := range uint8(8) {
		gb.Write(0xFF6B, uint8(pals[1][i>>1]>>((i&1)*8)))
	}

	// set obj palette 2
	gb.Write(0xFF6A, 0x80+0x8)
	for i := range uint8(8) {
		gb.Write(0xFF6B, uint8(pals[2][i>>1]>>((i&1)*8)))
	}
}

// hash 0x0 matches palette 43 from pal array
const STD_PAL_IDX = 43

func (gb *GameBoy) getCompPaletteId() uint8 {
	var (
		c          = &gb.Cartridge.Data
		oldLicense = (*c)[0x14B]
		newLicense = string((*c)[0x144:0x146])
	)

	if oldLicense != 1 && oldLicense != 0x33 {
		return STD_PAL_IDX
	}

	if oldLicense == 0x33 && newLicense != "01" {
		return STD_PAL_IDX
	}

	var sum uint8
	for i := 0x134; i < 0x144; i++ {
		sum += (*c)[i]
	}

	// check fourth letter pals first
	fourth := gb.Cartridge.Title[3]

	if id, ok := fourthLetterIds[struct {
		hash   uint8
		letter uint8
	}{sum, fourth}]; ok {
		return id
	}

	// check normal palettes
	if id, ok := standardIds[sum]; ok {
		return id
	}

	return STD_PAL_IDX
}

