type ColorPalette struct {
	Palette  [0x40]uint8
	Unpacked [0x40 / 2]uint32
	Idx      uint8
	Inc      bool
}

func (p *ColorPalette) Init() {
	for i := range len(p.Palette) {
		p.Palette[i] = 0xFF
	}
}

func (p *ColorPalette) update(idx uint8) {
	clr := binary.LittleEndian.Uint16(p.Palette[idx&^1:])

	p.Unpacked[idx>>1] = (uint32(clrLut[clr&0x1F]) |
		uint32(clrLut[(clr>>5)&0x1F])<<8 |
		uint32(clrLut[(clr>>10)&0x1F]<<16)) |
		(0xFF << 24)
}

